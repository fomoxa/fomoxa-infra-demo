using System.Collections.Generic;
using System.Linq;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;

namespace Fomoxa.Rpc.Generator
{
    internal static class Emitter
    {
        private const string Rpc = "global::Fomoxa.Rpc.";

        public static string HintName(Plan plan)
        {
            string space = plan.Interface.ContainingNamespace.IsGlobalNamespace ? "" : plan.Interface.ContainingNamespace.ToDisplayString() + ".";
            return $"{space}{plan.Service}.Rpc.g.cs";
        }

        public static string Emit(Plan plan)
        {
            var text = new StringBuilder();
            text.AppendLine("// <auto-generated/>");
            text.AppendLine("// GENERATED BY the fRPC source generator from [Service(\"" + plan.Service + "\")] on " + plan.Interface.Name);
            text.AppendLine("#nullable enable");
            text.AppendLine();
            bool scoped = !plan.Interface.ContainingNamespace.IsGlobalNamespace;
            string pad = scoped ? "    " : "";
            if (scoped)
            {
                text.AppendLine("namespace " + plan.Interface.ContainingNamespace.ToDisplayString());
                text.AppendLine("{");
            }
            string access = plan.Interface.DeclaredAccessibility == Accessibility.Public ? "public" : "internal";
            Methods(text, pad, access, plan);
            text.AppendLine();
            Client(text, pad, access, plan);
            text.AppendLine();
            Server(text, pad, access, plan);
            if (scoped)
            {
                text.AppendLine("}");
            }
            return text.ToString();
        }

        private static string Type(ITypeSymbol type) => type.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);

        private static string Adapter(Codec codec) => codec.Model.Name + "Adapter";

        private static string Descriptor(Rpc rpc) =>
            rpc.Kind == Kind.Unary
                ? $"{Rpc}UnaryMethod<{Type(rpc.Request.Model)}, {Type(rpc.Reply.Model)}>"
                : $"{Rpc}ServerStreamMethod<{Type(rpc.Request.Model)}, {Type(rpc.Reply.Model)}>";

        private static void Methods(StringBuilder text, string pad, string access, Plan plan)
        {
            string type = plan.Service + "Methods";
            text.AppendLine($"{pad}{access} static class {type}");
            text.AppendLine($"{pad}{{");
            foreach (Rpc rpc in plan.Rpcs)
            {
                var policy = new List<string>();
                if (rpc.Idempotent)
                {
                    policy.Add("Idempotent = true");
                }
                if (rpc.Deadline.HasValue)
                {
                    policy.Add($"Deadline = global::System.TimeSpan.FromMilliseconds({rpc.Deadline.Value})");
                }
                if (rpc.Requires != null)
                {
                    policy.Add($"Requires = {SymbolDisplay.FormatLiteral(rpc.Requires, true)}");
                }
                if (rpc.Idle.HasValue)
                {
                    policy.Add($"Idle = global::System.TimeSpan.FromMilliseconds({rpc.Idle.Value})");
                }
                if (rpc.Parallel)
                {
                    policy.Add("Parallel = true");
                }
                string details = string.Concat(rpc.Details.Select(detail => $"\n{pad}            .WithDetail({Adapter(detail)}.Instance)"));
                text.AppendLine($"{pad}    public static readonly {Descriptor(rpc)} {rpc.Name} =");
                text.AppendLine($"{pad}        new {Descriptor(rpc)}(");
                text.AppendLine($"{pad}            \"{plan.Service}.{rpc.Name}\",");
                text.AppendLine($"{pad}            {Adapter(rpc.Request)}.Instance,");
                text.AppendLine($"{pad}            {Adapter(rpc.Reply)}.Instance,");
                string written = policy.Count == 0 ? $"{Rpc}MethodPolicy.None" : $"new {Rpc}MethodPolicy {{ {string.Join(", ", policy)} }}";
                text.AppendLine($"{pad}            {written}){details};");
                text.AppendLine();
            }
            string all = string.Join(", ", plan.Rpcs.Select(rpc => rpc.Name + ".Method"));
            text.AppendLine($"{pad}    public static global::System.Collections.Generic.IReadOnlyList<{Rpc}Method> All {{ get; }} = new {Rpc}Method[] {{ {all} }};");
            text.AppendLine();
            text.AppendLine($"{pad}    public static {Rpc}RegistryBuilder Builder() =>");
            text.AppendLine($"{pad}        {Rpc}Registry.Builder({Type(plan.Void.Type)}.MessageId, {Type(plan.Error.Type)}.MessageId);");

            IEnumerable<Codec> codecs = plan.Rpcs
                .SelectMany(rpc => new[] { rpc.Request, rpc.Reply }.Concat(rpc.Details))
                .GroupBy(codec => codec.Model.Name)
                .Select(group => group.First())
                .OrderBy(codec => codec.Model.Name, System.StringComparer.Ordinal);
            foreach (Codec codec in codecs)
            {
                string model = Type(codec.Model);
                string implementation = Type(codec.Type);
                text.AppendLine();
                text.AppendLine($"{pad}    private sealed class {Adapter(codec)} : {Rpc}IRpcCodec<{model}>");
                text.AppendLine($"{pad}    {{");
                text.AppendLine($"{pad}        public static readonly {Adapter(codec)} Instance = new {Adapter(codec)}();");
                text.AppendLine();
                text.AppendLine($"{pad}        public uint MessageId => {implementation}.MessageId;");
                text.AppendLine();
                text.AppendLine($"{pad}        public byte[] Encode({model} value)");
                text.AppendLine($"{pad}        {{");
                text.AppendLine($"{pad}            var writer = new {Type(codec.Writer)}();");
                text.AppendLine($"{pad}            {implementation}.Encode(writer, value);");
                text.AppendLine($"{pad}            return writer.ToArray();");
                text.AppendLine($"{pad}        }}");
                text.AppendLine();
                text.AppendLine($"{pad}        public {model} Decode(global::System.ReadOnlySpan<byte> body)");
                text.AppendLine($"{pad}        {{");
                text.AppendLine($"{pad}            var value = new {model}();");
                text.AppendLine($"{pad}            var reader = new {Type(codec.Reader)}(body);");
                text.AppendLine($"{pad}            {implementation}.Decode(ref reader, ref value);");
                text.AppendLine($"{pad}            return value;");
                text.AppendLine($"{pad}        }}");
                text.AppendLine($"{pad}    }}");
            }
            text.AppendLine($"{pad}}}");
        }

        private static void Client(StringBuilder text, string pad, string access, Plan plan)
        {
            string type = plan.Service + "Client";
            string methods = plan.Service + "Methods";
            const string Connection = "global::Fomoxa.Rpc.Net.RpcConnection";
            text.AppendLine($"{pad}{access} sealed class {type}");
            text.AppendLine($"{pad}{{");
            text.AppendLine($"{pad}    private readonly {Connection} connection;");
            text.AppendLine();
            text.AppendLine($"{pad}    public {type}({Connection} connection)");
            text.AppendLine($"{pad}    {{");
            text.AppendLine($"{pad}        this.connection = connection ?? throw new global::System.ArgumentNullException(nameof(connection));");
            text.AppendLine($"{pad}    }}");
            text.AppendLine();
            string declares = string.Concat(plan.Rpcs.Select(rpc => $"\n{pad}        .Declare({methods}.{rpc.Name}.Method)"));
            text.AppendLine($"{pad}    public static {Rpc}RegistryBuilder Declare({Rpc}RegistryBuilder builder) =>");
            text.AppendLine($"{pad}        builder{declares};");
            text.AppendLine();
            text.AppendLine($"{pad}    public static {Rpc}RegistryBuilder Registry() => Declare({methods}.Builder());");
            foreach (Rpc rpc in plan.Rpcs)
            {
                string request = Type(rpc.Request.Model);
                string reply = Type(rpc.Reply.Model);
                string parameters = rpc.NamedRequest ? $"{request} request, {Rpc}CallOptions? options = null" : $"{Rpc}CallOptions? options = null";
                string argument = rpc.NamedRequest ? "request" : $"new {request}()";
                text.AppendLine();
                if (rpc.Kind == Kind.Unary)
                {
                    text.AppendLine($"{pad}    public global::System.Threading.Tasks.Task<{reply}> {rpc.Name}Async({parameters}) =>");
                    text.AppendLine($"{pad}        connection.Unary({methods}.{rpc.Name}, {argument}, options);");
                }
                else
                {
                    text.AppendLine($"{pad}    public global::System.Collections.Generic.IAsyncEnumerable<{reply}> {rpc.Name}({parameters}) =>");
                    text.AppendLine($"{pad}        connection.ServerStream({methods}.{rpc.Name}, {argument}, options);");
                }
            }
            text.AppendLine($"{pad}}}");
        }

        private static void Server(StringBuilder text, string pad, string access, Plan plan)
        {
            string type = plan.Service + "Server";
            string methods = plan.Service + "Methods";
            string handler = Type(plan.Interface);
            text.AppendLine($"{pad}{access} sealed class {type}");
            text.AppendLine($"{pad}{{");
            text.AppendLine($"{pad}    private readonly {handler} handler;");
            text.AppendLine();
            text.AppendLine($"{pad}    public {type}({handler} handler)");
            text.AppendLine($"{pad}    {{");
            text.AppendLine($"{pad}        this.handler = handler ?? throw new global::System.ArgumentNullException(nameof(handler));");
            text.AppendLine($"{pad}    }}");
            text.AppendLine();
            text.AppendLine($"{pad}    public {Rpc}RegistryBuilder Register({Rpc}RegistryBuilder builder)");
            text.AppendLine($"{pad}    {{");
            foreach (Rpc rpc in plan.Rpcs)
            {
                string request = Type(rpc.Request.Model);
                string reply = Type(rpc.Reply.Model);
                string passed = rpc.NamedRequest ? "request" : "";
                string withContext = rpc.Context ? (rpc.NamedRequest ? "context, request" : "context") : passed;
                string lambda;
                switch (rpc.Form)
                {
                    case Form.Later:
                        lambda = $"({Rpc}Reply<{reply}> reply, {request} request) => handler.{rpc.Name}(reply{(rpc.NamedRequest ? ", request" : "")})";
                        break;
                    case Form.Stream:
                        lambda = $"({Rpc}ItemStream<{reply}> stream, {request} request) => handler.{rpc.Name}(stream{(rpc.NamedRequest ? ", request" : "")})";
                        break;
                    case Form.NowVoid:
                        lambda = $"({Rpc}CallContext context, {request} request) =>\n{pad}            {{\n{pad}                handler.{rpc.Name}({withContext});\n{pad}                return new {reply}();\n{pad}            }}";
                        break;
                    default:
                        lambda = $"({Rpc}CallContext context, {request} request) => handler.{rpc.Name}({withContext})";
                        break;
                }
                text.AppendLine($"{pad}        builder = builder.Serve({methods}.{rpc.Name}, {lambda});");
            }
            text.AppendLine($"{pad}        return builder;");
            text.AppendLine($"{pad}    }}");
            text.AppendLine();
            text.AppendLine($"{pad}    public {Rpc}RegistryBuilder Registry() =>");
            text.AppendLine($"{pad}        Register({methods}.Builder().Health({Type(plan.HealthRequest.Type)}.MessageId, {Type(plan.HealthResponse.Type)}.MessageId));");
            text.AppendLine($"{pad}}}");
        }
    }
}
